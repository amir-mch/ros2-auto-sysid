"""ROS 2 parameter exporter for calibrated dynamics configurations."""

from __future__ import annotations

import datetime
from pathlib import Path
from typing import Any, Dict, Optional
import yaml


def export_to_ros2_yaml(
    params: Dict[str, float],
    output_path: str | Path,
    node_name: str = "vehicle_dynamics_node",
    metadata: Optional[Dict[str, Any]] = None,
) -> Path:
    """Export calibrated parameter dictionary to ROS 2 parameter YAML.

    Args:
        params: Key-value mapping of physical parameters.
        output_path: Target file path for the YAML.
        node_name: Target ROS 2 node namespace.
        metadata: Optional extra fields (RMSE, timestamps, notes).

    Returns:
        Path to the saved YAML file.
    """
    path = Path(output_path)
    path.parent.mkdir(parents=True, exist_ok=True)

    header_comment = (
        f"# Calibrated Physical Dynamics Parameters\n"
        f"# Generated by ros2-auto-sysid on {datetime.datetime.now(datetime.timezone.utc).isoformat()}\n"
    )

    clean_params = {k: float(v) for k, v in params.items()}

    content: Dict[str, Any] = {
        node_name: {
            "ros__parameters": {
                "dynamics": clean_params,
            }
        }
    }

    if metadata:
        content[node_name]["ros__parameters"]["metadata"] = metadata

    with open(path, "w", encoding="utf-8") as f:
        f.write(header_comment)
        yaml.dump(content, f, default_flow_style=False, sort_keys=False)

    return path


def load_ros2_yaml(yaml_path: str | Path, node_name: str = "vehicle_dynamics_node") -> Dict[str, float]:
    """Load dynamics parameters from a ROS 2 YAML configuration file."""
    path = Path(yaml_path)
    with open(path, "r", encoding="utf-8") as f:
        data = yaml.safe_load(f)

    if node_name in data and "ros__parameters" in data[node_name]:
        params_section = data[node_name]["ros__parameters"].get("dynamics", {})
        return {str(k): float(v) for k, v in params_section.items()}
    elif "/**" in data and "ros__parameters" in data["/**"]:
        params_section = data["/**"]["ros__parameters"].get("dynamics", {})
        return {str(k): float(v) for k, v in params_section.items()}
    else:
        raise KeyError(f"Could not locate parameters for node '{node_name}' in {yaml_path}")
